-- This SQL RPC increments the single global counter atomically, not via a
-- browser-side read/modify/write that loses updates.
create or replace function public.bump_hexfield_sim(
  p_cycles bigint default 0, p_trials bigint default 0,
  p_improvements bigint default 0, p_learning bigint default 0,
  p_best_score real default 0, p_last_field text default '',
  p_last_lever text default ''
)
returns void
language plpgsql volatile security definer set search_path = ''
as $$
begin
  if (select auth.uid()) is null then raise exception 'authentication required' using errcode = '42501'; end if;
  update public.hexfield_sim_progress
  set total_cycles = total_cycles + least(50000, greatest(0, coalesce(p_cycles,0))),
      total_trials = total_trials + least(200000, greatest(0, coalesce(p_trials,0))),
      total_improvements = total_improvements + least(50000, greatest(0, coalesce(p_improvements,0))),
      learning_events = learning_events + least(50000, greatest(0, coalesce(p_learning,0))),
      best_score = greatest(best_score, least(1, greatest(0, coalesce(p_best_score,0)))),
      updated_at = now()
  where id = true;
end;
$$;
revoke all on function public.bump_hexfield_sim(bigint,bigint,bigint,bigint,real,text,text) from public, anon;
grant execute on function public.bump_hexfield_sim(bigint,bigint,bigint,bigint,real,text,text) to authenticated;
